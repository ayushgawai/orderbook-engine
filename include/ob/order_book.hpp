#pragma once
#include <cstdint>
#include <functional>
#include <list>
#include <map>
#include <optional>
#include <unordered_map>
#include <vector>

namespace ob {

using OrderId = std::uint64_t;
using Price = std::int64_t;  // integer ticks, never floating point
using Qty = std::int64_t;

enum class Side : std::uint8_t { Buy, Sell };
enum class TimeInForce : std::uint8_t { GTC, IOC };

struct Fill {
  OrderId maker, taker;
  Price price;
  Qty qty;
};

struct Level {
  Price price;
  Qty total;
  int orders;
};

// Single-instrument limit order book with price-time priority.
//  - Each price level is a FIFO list. An id -> (side, price, list iterator) index gives O(1) cancel.
//  - Levels sit in ordered maps: best bid is the highest key, best ask the lowest.
//  - Aggressive orders match against the opposite side before any remainder rests.
class OrderBook {
 public:
  explicit OrderBook(std::size_t expected_orders = 1 << 16);

  // Returns fills generated by this order. GTC remainder rests, IOC remainder is cancelled.
  std::vector<Fill> add_limit(OrderId id, Side side, Price price, Qty qty, TimeInForce tif = TimeInForce::GTC);
  std::vector<Fill> add_market(OrderId id, Side side, Qty qty);
  bool cancel(OrderId id);
  // Reducing quantity keeps queue priority. Increasing it or changing price moves the order to the back.
  std::vector<Fill> modify(OrderId id, Price new_price, Qty new_qty);

  std::optional<Price> best_bid() const;
  std::optional<Price> best_ask() const;
  std::vector<Level> depth(Side side, std::size_t levels) const;
  std::size_t resting_orders() const { return index_.size(); }
  bool crossed() const;

 private:
  struct Order {
    OrderId id;
    Qty qty;
  };
  using Queue = std::list<Order>;
  struct LevelQueue {
    Queue queue;
    Qty total = 0;
  };
  using Bids = std::map<Price, LevelQueue, std::greater<Price>>;
  using Asks = std::map<Price, LevelQueue, std::less<Price>>;
  struct Locator {
    Side side;
    Price price;
    Queue::iterator it;
  };

  template <typename Book>
  void match(Book& book, OrderId taker, Price limit, bool is_buy, Qty& remaining, std::vector<Fill>& fills);
  void rest(OrderId id, Side side, Price price, Qty qty);

  Bids bids_;
  Asks asks_;
  std::unordered_map<OrderId, Locator> index_;
};

}  // namespace ob
